"""Guest load layout of the Pokémon Violet modules (any dump version): the single source of truth for gen.py bases and the runtime loader.

Horizon's loader maps modules back to back in this order: rtld, main, subsdk*, sdk. We keep that order, start
at 0x7000000000 like LAS Recomp, and align each module to 2 MiB. The Zelda layout (sdk at +64 MiB) does NOT fit:
Pokémon's main is ~68 MiB.
Usage: python layout.py [exefs_dir]  -> prints the table (and checks the modules don't overlap)
"""
import os
import sys

from nso import Nso

GUEST_BASE = 0x7000000000
ALIGN = 0x200000
ORDER = ['main', 'subsdk0', 'sdk']  # rtld is replaced by host code (HLE), as in LAS Recomp


def layout(exefs):
    out, at = [], GUEST_BASE
    for name in ORDER:
        path = os.path.join(exefs, name)
        if not os.path.exists(path):
            continue
        n = Nso(path)
        out.append((name, at, n.size, n.build_id[:16]))
        at = (at + n.size + ALIGN - 1) & ~(ALIGN - 1)
    return out, at


def header(exefs, version):
    mods, _ = layout(exefs)
    lines = ['// Generated by recomp/layout.py --header: do not edit.', '#pragma once']
    for name, base, size, bid in mods:
        lines += [f'#define PV_BASE_{name} {base:#x}ull', f'#define PV_BUILD_{name} "{bid}"']
    lines.append(f'#define PVGAME_ID "{version} ' + ' '.join(f'{n}:{b}' for n, _, _, b in mods) + '"')
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    # python layout.py [exefs_dir] [--header out.h --version v400]
    args = [a for a in sys.argv[1:]]
    exefs = args[0] if args and not args[0].startswith('--') else os.path.join('..', '..', 'dumps', 'base', 'exefs')
    if '--header' in args:
        out = args[args.index('--header') + 1]
        ver = args[args.index('--version') + 1] if '--version' in args else 'dev'
        open(out, 'w', encoding='utf-8').write(header(exefs, ver))
        print(f'wrote {out}')
        sys.exit(0)
    mods, end = layout(exefs)
    for name, base, size, bid in mods:
        print(f'{name:8} base={base:#x} size={size:#x} ({size / 2**20:.1f} MiB) end={base + size:#x} build={bid}')
    print(f'modules end at {end:#x} ({(end - GUEST_BASE) / 2**20:.1f} MiB)')
